"""Offline structural validator for OCSF events against a local clone of ocsf-schema.

Checks: required attributes present, no attributes outside the class/profiles/objects,
enum *_id values defined, object-vs-scalar types, arrays where the dictionary says is_array.

Usage:
    git clone --depth 1 --branch v1.10.0 https://github.com/ocsf/ocsf-schema.git
    python scripts/validate_ocsf.py ocsf-schema output/incident_24017.ocsf.json
"""
from __future__ import annotations

import json
import sys
from functools import lru_cache
from pathlib import Path

SCALAR_SUFFIX = "_t"


class Schema:
    def __init__(self, root: str):
        self.root = Path(root)
        d = json.loads((self.root / "dictionary.json").read_text())
        self.dict_attrs = d["attributes"]
        self.types = d["types"]["attributes"]
        self.objects = {p.stem: json.loads(p.read_text()) for p in (self.root / "objects").glob("*.json")}
        self.objects.update({json.loads(p.read_text())["name"]: json.loads(p.read_text())
                             for p in (self.root / "objects").glob("*.json")})
        self.events = {}
        for p in (self.root / "events").rglob("*.json"):
            j = json.loads(p.read_text())
            self.events[j["name"]] = j
        # observable.type_id is generated by the schema compiler from types/objects/attributes
        obs = {"0": "Unknown", "99": "Other"}
        for src in (self.types, self.dict_attrs):
            for k, v in src.items():
                if "observable" in v:
                    obs[str(v["observable"])] = k
        for o in self.objects.values():
            if "observable" in o:
                obs[str(o["observable"])] = o["name"]
            for k, v in o.get("attributes", {}).items():
                if isinstance(v, dict) and "observable" in v:
                    obs[str(v["observable"])] = f"{o['name']}.{k}"
        self.observable_ids = obs
        self.profiles = {p.stem: json.loads(p.read_text()) for p in (self.root / "profiles").glob("*.json")}

    def _include(self, inc: str) -> dict:
        path = self.root / inc.lstrip("/")
        return json.loads(path.read_text()).get("attributes", {})

    def _merge(self, spec: dict, attrs: dict, profiles: tuple[str, ...] | None = None) -> dict:
        out = {}
        inc = attrs.get("$include")
        for i in ([inc] if isinstance(inc, str) else inc or []):
            if profiles is not None and i.startswith("profiles/") and Path(i).stem not in profiles:
                continue  # profile not applied to this event: its attributes are not in scope
            out.update(self._include(i))
        for k, v in attrs.items():
            if k != "$include":
                out[k] = {**out.get(k, {}), **v}
        return out

    @lru_cache(maxsize=None)
    def event_attrs(self, name: str, profiles: tuple[str, ...]) -> dict:
        chain, cur = [], self.events[name]
        while cur:
            chain.append(cur)
            cur = self.events.get(cur.get("extends")) if cur.get("extends") else None
        merged: dict = {}
        for spec in reversed(chain):
            merged.update(self._merge(spec, spec.get("attributes", {}), profiles))
        for p in profiles:
            if p in self.profiles:
                for k, v in self.profiles[p]["attributes"].items():
                    if k != "$include":
                        merged.setdefault(k, v)
        return merged

    @lru_cache(maxsize=None)
    def object_attrs(self, name: str) -> dict:
        chain, cur = [], self.objects.get(name)
        while cur:
            chain.append(cur)
            ext = cur.get("extends")
            cur = self.objects.get(ext) if ext and ext != "object" else None
        merged: dict = {}
        for spec in reversed(chain):
            merged.update(self._merge(spec, spec.get("attributes", {})))
        return merged

    def attr_def(self, key: str, local: dict) -> dict:
        return {**self.dict_attrs.get(key, {}), **local}


def validate(schema: Schema, event: dict) -> list[str]:
    errors: list[str] = []
    cats = json.loads((schema.root / "categories.json").read_text())["attributes"]
    def category(e: dict) -> str | None:
        while e and not e.get("category"):
            e = schema.events.get(e.get("extends") or "")
        return e.get("category") if e else None

    cls = next(e for e in schema.events.values()
               if "uid" in e and category(e) in cats
               and cats[category(e)]["uid"] * 1000 + e["uid"] == event.get("class_uid"))
    profiles = tuple(event.get("metadata", {}).get("profiles", []))
    attrs = schema.event_attrs(cls["name"], profiles)
    _check(schema, event, attrs, cls["name"], errors, top=True)
    return errors


def _check(schema: Schema, obj: dict, attrs: dict, path: str, errors: list[str], top=False) -> None:
    for k, local in attrs.items():
        if local.get("requirement") == "required" and k not in obj:
            errors.append(f"{path}: missing required '{k}'")
    for k, v in obj.items():
        if k not in attrs:
            errors.append(f"{path}: unknown attribute '{k}'")
            continue
        d = schema.attr_def(k, attrs[k])
        t = d.get("type", "")
        if d.get("is_array") and not isinstance(v, list):
            errors.append(f"{path}.{k}: expected array")
            continue
        values = v if isinstance(v, list) else [v]
        for i, item in enumerate(values):
            p = f"{path}.{k}" + (f"[{i}]" if isinstance(v, list) else "")
            if t.endswith(SCALAR_SUFFIX) or t == "json_t":
                if isinstance(item, dict) and t != "json_t":
                    errors.append(f"{p}: expected scalar {t}, got object")
                enum = d.get("enum")
                if k == "type_id" and path.split(".")[-1].startswith("observables"):
                    enum = schema.observable_ids
                if enum and k.endswith("_id") and str(item) not in enum:
                    errors.append(f"{p}: {item} not in enum {list(enum)}")
            elif t in schema.objects:
                if not isinstance(item, dict):
                    errors.append(f"{p}: expected object {t}")
                elif k != "unmapped" and t not in ("object",):
                    _check(schema, item, schema.object_attrs(t), p, errors)


def main() -> int:
    schema = Schema(sys.argv[1])
    bad = 0
    for f in sys.argv[2:]:
        data = json.loads(Path(f).read_text())
        for ev in data if isinstance(data, list) else [data]:
            errs = validate(schema, ev)
            print(f"{f}: {'OK' if not errs else f'{len(errs)} issue(s)'}")
            for e in errs:
                print("  -", e)
            bad += bool(errs)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
